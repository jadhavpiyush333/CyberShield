
from cybershield.schemas import DetectionResult


WEIGHTS = {
    "port_scan": 45,
    "brute_force": 50,
    "dos": 70,
    "ddos": 85,
    "botnet": 80,
    "malicious_dns": 65,
    "suspicious_outbound": 45,
    "repeated_auth_failure": 40,
}


def detect(event, model_result=None):
    """Use the trained network IDS when a valid prediction is available."""

    if isinstance(model_result, dict) and "prediction" in model_result:
        prediction = int(model_result["prediction"])
        attack_probability = float(model_result["attack_probability"])
        threshold = float(model_result.get("threshold", 0.61))
        model_version = model_result.get(
            "model_version",
            "network-ids-optimized-1.0",
        )

        attack_probability = max(0.0, min(1.0, attack_probability))
        is_attack = prediction == 1
        risk_score = round(attack_probability * 100, 2)

        if is_attack:
            severity = (
                "critical" if attack_probability >= 0.80
                else "high" if attack_probability >= threshold
                else "medium"
            )
            threat_type = "network_intrusion"
            actions = [
                "Review IDS and firewall logs.",
                "Investigate the source and destination of the flow.",
                "Isolate confirmed malicious hosts when appropriate.",
            ]
        else:
            severity = "low"
            threat_type = "normal_network_activity"
            actions = ["Continue monitoring network activity."]

        return DetectionResult(
            threat_type=threat_type,
            severity=severity,
            risk_score=risk_score,
            confidence=(
                attack_probability
                if is_attack
                else 1.0 - attack_probability
            ),
            evidence=[
                "Prediction generated by the trained network IDS.",
                f"Predicted attack: {is_attack}",
                f"Attack probability: {attack_probability:.4f}",
                f"Classification threshold: {threshold:.2f}",
                f"Event type: {event.get('event_type', 'network flow')}",
            ],
            recommended_actions=actions,
            model_version=model_version,
        )

    # Fall back to heuristics when no usable ML prediction is available.
    event_type = str(event.get("event_type", "")).lower()
    score = WEIGHTS.get(event_type, 15)
    evidence = [f"Network event: {event_type or 'unknown'}"]

    for key in (
        "connections_per_minute",
        "failed_logins",
        "unique_ports",
        "bytes_per_second",
    ):
        if key in event:
            evidence.append(f"{key}={event[key]}")

    if event.get("connections_per_minute", 0) > 500:
        score += 15

    if event.get("failed_logins", 0) > 20:
        score += 15

    score = min(100, score)
    severity = (
        "critical" if score >= 80
        else "high" if score >= 60
        else "medium" if score >= 35
        else "low"
    )

    return DetectionResult(
        threat_type="network_intrusion",
        severity=severity,
        risk_score=score,
        confidence=min(0.99, 0.55 + score / 220),
        evidence=evidence,
        recommended_actions=(
            [
                "Review IDS and firewall logs.",
                "Investigate suspicious hosts.",
                "Block confirmed malicious destinations.",
            ]
            if score >= 35
            else ["Continue monitoring."]
        ),
        model_version="heuristic-1.0",
    )
